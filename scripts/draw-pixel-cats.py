#!/usr/bin/env python3
"""Draw the two 28-pixel keyboard sprites and export to both mobile bundles."""
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
ANDROID = ROOT / "Android/app/src/main/res/drawable-nodpi"


def draw_cat(mimimo):
    image = Image.new("RGBA", (28, 28))
    draw = ImageDraw.Draw(image)
    p = draw.polygon
    r = draw.rectangle
    if mimimo:
        ink, fur, shine = "#17151e", "#282431", "#494053"
        p([(2, 23), (2, 15), (4, 11), (4, 3), (6, 2), (11, 7), (15, 7),
           (20, 1), (22, 1), (24, 4), (25, 12), (26, 15), (26, 23),
           (24, 26), (19, 27), (9, 27), (4, 26)], ink)
        p([(3, 21), (3, 16), (5, 11), (5, 5), (7, 5), (11, 9), (16, 8),
           (21, 3), (23, 6), (24, 13), (25, 16), (25, 21), (23, 24), (5, 24)], fur)
        p([(6, 5), (10, 9), (6, 10)], shine)
        p([(18, 8), (21, 4), (23, 10)], shine)
        r((7, 11, 9, 11), "#363140")
        r((20, 10, 22, 10), "#363140")
        p([(6, 15), (12, 16), (11, 19), (8, 19)], "#f7d986")
        p([(16, 15), (22, 12), (21, 17), (19, 18), (17, 17)], "#ffe2a2")
        r((10, 16, 10, 18), ink)
        r((20, 13, 20, 16), ink)
        r((13, 20, 14, 20), "#ce8f91")
        draw.line([(11, 21), (12, 22), (13, 22), (14, 21), (15, 22), (16, 22), (17, 21)], "#b6a1a5")
        draw.line([(4, 20), (7, 19)], "#c0aeb2")
        draw.line([(4, 22), (7, 21)], "#8d7c8f")
        r((7, 25, 11, 26), shine)
        r((17, 25, 21, 26), shine)
    else:
        outline, fur, shadow = "#634655", "#ffebd7", "#e6ba9c"
        p([(2, 23), (2, 14), (4, 10), (4, 3), (6, 2), (11, 7), (16, 7),
           (21, 2), (23, 3), (24, 11), (26, 15), (26, 22), (24, 25), (20, 27),
           (8, 27), (4, 25)], outline)
        p([(5, 10), (5, 4), (7, 4), (11, 8), (17, 8), (21, 4), (22, 4), (23, 11)], "#a37465")
        p([(6, 7), (6, 5), (9, 8)], "#e0a68d")
        p([(19, 8), (22, 5), (22, 9)], "#e0a68d")
        p([(3, 21), (3, 15), (5, 12), (8, 10), (12, 9), (17, 9), (22, 11),
           (24, 14), (25, 17), (25, 21), (23, 24), (19, 25), (8, 25), (5, 24)], fur)
        p([(8, 15), (11, 13), (17, 13), (21, 16), (21, 20), (18, 23),
           (10, 23), (7, 20), (7, 17)], "#a6796c")
        r((9, 15, 11, 18), "#2f3445")
        r((17, 15, 19, 18), "#2f3445")
        r((9, 17, 10, 19), "#83cbdd")
        r((17, 17, 18, 19), "#83cbdd")
        draw.point((10, 15), "#fff7ed")
        draw.point((18, 15), "#fff7ed")
        draw.line([(11, 20), (12, 21), (13, 21), (14, 20), (15, 21), (16, 21), (17, 20)], "#452e3c")
        r((4, 19, 6, 20), "#f1b4ae")
        r((22, 19, 24, 20), "#f1b4ae")
        r((7, 24, 11, 26), shadow)
        r((17, 24, 21, 26), shadow)
        r((8, 25, 10, 26), "#9f6e64")
        r((18, 25, 20, 26), "#9f6e64")
    return image


if __name__ == "__main__":
    for name in ("mimimo", "momo"):
        draw_cat(name == "mimimo").save(ANDROID / f"cat_pixel_{name}.png", optimize=True)
