#!/usr/bin/env python3
"""Writes GlyphCatArt.kt from the prototype's cat sprites (design-preview/specs/cats-next.json): the two cats as pixel grids.

    python3 -I scripts/gen_glyph_cat_art.py [path/to/cats-next.json]

Mimi is 22 x 16 and Momo 20 x 15; each has six poses and sixteen faces. The file it writes is not edited by hand."""
import json, os, sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# The prototype lives beside the repository (read-only); a worktree sits one level deeper, so look for it upward.
def find():
    here = root
    while here != os.path.dirname(here):
        cand = os.path.join(here, "design-preview", "specs", "cats-next.json")
        if os.path.exists(cand): return cand
        here = os.path.dirname(here)
    sys.exit("cats-next.json not found: pass its path")
src = sys.argv[1] if len(sys.argv) > 1 else find()
out = os.path.join(root, "Android/app/src/main/java/com/krysta1ll/meowpuut/android/ime/glyph/GlyphCatArt.kt")
d = json.load(open(src))

def pal(h): return "0xFF%s.toInt()" % h.lstrip("#").upper()

lines = ["package com.krysta1ll.meowpuut.android.ime.glyph", "",
  "// Generated by scripts/gen_glyph_cat_art.py from design-preview/specs/cats-next.json: the two cats as pixel grids (Mimi 22 x 16, Momo 20 x 15),",
  "// one letter per pixel. Do not edit by hand; the letters name colours in [GlyphCatArt.PALETTE].", "",
  "internal object GlyphCatArt {", "    /** Pixel letter to opaque ARGB. */", "    val PALETTE: Map<Char, Int> = mapOf("]
for k, v in d["pal"].items(): lines.append("        '%s' to %s," % (k, pal(v)))
lines += ["    )", ""]
for cat in ("mimi", "momo"):
    lines.append("    val %s: Map<String, List<String>> = mapOf(" % cat.upper())
    for pose, rows in d[cat].items():
        lines.append('        "%s" to listOf(' % pose)
        for r in rows: lines.append('            "%s",' % r)
        lines.append("        ),")
    lines += ["    )", ""]
lines.append("    /** Face by face: the pixels (row, column, letters) that replace the cat's own eyes and mouth. */")
lines.append("    val FACES: Map<String, Map<String, List<Triple<Int, Int, String>>>> = mapOf(")
for cat in ("mimi", "momo"):
    lines.append('        "%s" to mapOf(' % cat)
    for face, items in d["faces"][cat].items():
        lines.append('            "%s" to listOf(%s),' % (face, ", ".join('Triple(%d, %d, "%s")' % (r, c, s) for r, c, s in items)))
    lines.append("        ),")
lines += ["    )", "}", ""]
open(out, "w").write("\n".join(lines))
print("wrote", out)
