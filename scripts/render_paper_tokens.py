#!/usr/bin/env python3
"""Write the paper colour tokens of the app pages (Kami-Biyori) to every client.

    python3 scripts/render_paper_tokens.py            write every client from assets/brand/paper/paper-tokens.json
    python3 scripts/render_paper_tokens.py --check    write nothing; exit 1 if a client's file differs
    python3 scripts/render_paper_tokens.py --root DIR use DIR as the repo root

Writes (the output is deterministic):
  Sources/PaperTokens.swift                                          this repo
  ../ios-art/Sources/PaperTokens.swift                               the iOS repo, if it sits next to this one
                                                                     (or pass --ios-root DIR)
  Android/app/src/main/java/com/krysta1ll/meowpuut/android/app/PaperTokens.kt

Only App pages use these colours (iOS companion app, macOS Studio window,
Android settings and SkinGallery). Keyboards and candidate windows keep their
own palettes.
"""
import argparse
import json
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
TOKENS = ("paper", "paper2", "ink", "inkSecondary", "pill", "pillText", "stamp", "tapeA", "tapeB", "grain", "shadowWarm")
SOURCE = "assets/brand/paper/paper-tokens.json"
HEADER = f"Generated by scripts/render_paper_tokens.py from {SOURCE}. Do not edit."


def stop(message):
    raise SystemExit("render_paper_tokens: " + message)


def parse(h):
    h = h.lstrip("#")
    if len(h) not in (6, 8):
        stop(f"bad colour {h!r}")
    rgb = int(h[:6], 16)
    alpha = int(h[6:], 16) if len(h) == 8 else 255
    return rgb, alpha


def load(root):
    with open(os.path.join(root, SOURCE), encoding="utf-8") as f:
        data = json.load(f)
    for mode in ("light", "dark"):
        for theme in data["themes"]:
            missing = [k for k in TOKENS if k not in data["modes"][mode][theme]]
            if missing:
                stop(f"{mode}/{theme} is missing {missing}")
    return data


def swift(data):
    out = [f"// {HEADER}", "import SwiftUI", "import CoreGraphics", ""]
    out += [
        "/// An sRGB colour with alpha, from the token file.",
        "struct PaperColor: Equatable {",
        "    let red: Double, green: Double, blue: Double, alpha: Double",
        "    /// `rgb` is 0xRRGGBB; `alpha` is 0...255.",
        "    init(_ rgb: UInt32, alpha: UInt8 = 255) {",
        "        red = Double((rgb >> 16) & 0xFF) / 255",
        "        green = Double((rgb >> 8) & 0xFF) / 255",
        "        blue = Double(rgb & 0xFF) / 255",
        "        self.alpha = Double(alpha) / 255",
        "    }",
        "    var color: Color { Color(.sRGB, red: red, green: green, blue: blue, opacity: alpha) }",
        "    var cgColor: CGColor { CGColor(srgbRed: red, green: green, blue: blue, alpha: alpha) }",
        "}",
        "",
        "/// The six colour themes. Raw values match `CandidatePalette` and the stored palette ids.",
        "enum PaperTheme: String, CaseIterable, Identifiable {",
        "    case " + ", ".join(data["themes"]),
        "    var id: String { rawValue }",
        "}",
        "",
        "/// One theme in one appearance.",
        "struct PaperPalette: Equatable {",
    ]
    out += [f"    let {k}: PaperColor" for k in TOKENS]
    out += ["}", "", "enum PaperTokens {"]
    out += [
        "    /// Opacity of tapeA / tapeB when laid over the paper. Contrast was checked at this opacity.",
        f"    static let tapeAlpha: Double = {data['tapeAlpha']}",
        "    /// Name of the tileable 128x128 grain image in the asset catalog (white, alpha is the grain). Tint it with `PaperPalette.grain`.",
        "    static let grainImageName = \"paper_grain\"",
        "",
        "    static func palette(_ theme: PaperTheme, dark: Bool) -> PaperPalette {",
        "        switch (theme, dark) {",
    ]
    for mode in ("light", "dark"):
        for theme in data["themes"]:
            t = data["modes"][mode][theme]
            args = []
            for k in TOKENS:
                rgb, a = parse(t[k])
                args.append(f"{k}: PaperColor(0x{rgb:06X}" + (f", alpha: {a})" if a != 255 else ")"))
            out.append(f"        case (.{theme}, {'true' if mode == 'dark' else 'false'}):")
            out.append("            PaperPalette(" + ", ".join(args) + ")")
    out += ["        }", "    }", "}", ""]
    return "\n".join(out)


def kotlin(data):
    out = [
        f"// {HEADER}",
        "package com.krysta1ll.meowpuut.android.app",
        "",
        "/** The six colour themes. [key] matches `Palette.key` in the IME package and the stored palette id. */",
        "enum class PaperTheme(val key: String) {",
        "    " + ", ".join(f'{t.upper()}("{t}")' for t in data["themes"]) + ";",
        "",
        "    companion object {",
        "        fun fromKey(key: String?): PaperTheme = values().firstOrNull { it.key == key } ?: ROSE",
        "    }",
        "}",
        "",
        "/** One theme in one appearance. Every colour is a packed ARGB int. */",
        "data class PaperPalette(",
    ]
    out += [f"    val {k}: Int," for k in TOKENS]
    out += [")", "", "object PaperTokens {"]
    out += [
        "    /** Opacity of tapeA / tapeB when laid over the paper. Contrast was checked at this opacity. */",
        f"    const val TAPE_ALPHA = {data['tapeAlpha']}f",
        "",
        "    /** Drawable name of the tileable 128x128 grain (white, alpha is the grain): R.drawable.paper_grain. Tint it with [PaperPalette.grain]. */",
        '    const val GRAIN_DRAWABLE = "paper_grain"',
        "",
        "    fun palette(theme: PaperTheme, dark: Boolean): PaperPalette = when (theme) {",
    ]
    for theme in data["themes"]:
        out.append(f"        PaperTheme.{theme.upper()} -> if (dark) {theme}Dark else {theme}Light")
    out += ["    }", ""]
    for mode in ("light", "dark"):
        for theme in data["themes"]:
            t = data["modes"][mode][theme]
            out.append(f"    private val {theme}{mode.capitalize()} = PaperPalette(")
            for k in TOKENS:
                rgb, a = parse(t[k])
                out.append(f"        {k} = 0x{a:02X}{rgb:06X}.toInt(),")
            out.append("    )")
    out += ["}", ""]
    return "\n".join(out)


def write(path, text, check):
    old = None
    if os.path.exists(path):
        with open(path, encoding="utf-8") as f:
            old = f.read()
    if old == text:
        print("same   " + path)
        return False
    if check:
        print("DIFFERS " + path)
        return True
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote  " + path)
    return False


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default=ROOT)
    ap.add_argument("--ios-root", default=None, help="the iOS repo (default: ../ios-art next to this repo, if present)")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    data = load(args.root)
    swift_text = swift(data)
    targets = [
        (os.path.join(args.root, "Sources", "PaperTokens.swift"), swift_text),
        (os.path.join(args.root, "Android/app/src/main/java/com/krysta1ll/meowpuut/android/app/PaperTokens.kt"), kotlin(data)),
    ]
    ios = args.ios_root or os.path.join(os.path.dirname(args.root), "ios-art")
    if os.path.isdir(os.path.join(ios, "Sources")):
        targets.append((os.path.join(ios, "Sources", "PaperTokens.swift"), swift_text))
    elif args.ios_root:
        stop(f"no Sources directory in {ios}")
    differs = [write(p, t, args.check) for p, t in targets]
    return 1 if any(differs) else 0


if __name__ == "__main__":
    sys.exit(main())
